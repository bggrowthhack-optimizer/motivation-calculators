/**
 * Шаблон калькулятора РОПа (руководитель отдела продаж) — нормы.
 * Обезличенный черновик: не привязан к клиенту, все цифры УСЛОВНЫЕ,
 * их нужно заменить на реальные политики конкретной сети.
 *
 * Модель: ЗП РОПа = оклад + % от выручки куста + KPI-премии.
 *
 *   • ГРЕЙД (ставка %) берётся от ВЫПОЛНЕНИЯ ПЛАНА КУСТА в целом (в %).
 *     Деньги считаются как ставка × выручка куста (не личная).
 *   • KPI-премии — бинарные, без градаций: план по показателю выполнен —
 *     фиксированная премия, не выполнен — ноль. Два KPI: средний чек и
 *     конверсия (рецепт → заказ).
 *
 * Правка под клиента: изменить DEFAULT_NORMS здесь (и заголовки в index.html).
 *
 * Грейды: массив ступеней {порог, ставка}, отсортирован по порогу.
 * Первый элемент — базовая ставка (порог 0, «ниже всех порогов»).
 */
(function (global) {
  var DEFAULT_NORMS = {
    оклад: 60000,
    грейды: [
      { порог: 0,   ставка: 0.004 },  // план куста < 80%
      { порог: 80,  ставка: 0.006 },
      { порог: 100, ставка: 0.008 },
      { порог: 110, ставка: 0.010 }   // перевыполнение
    ],
    kpiЧек: {
      план: 12000,     // плановый средний чек, ₽
      премия: 10000    // выплачивается, если факт не ниже плана
    },
    kpiКонверсия: {
      план: 40,        // плановая конверсия рецепт → заказ, %
      премия: 10000    // выплачивается, если факт не ниже плана
    }
  };

  function norms() { return JSON.parse(JSON.stringify(DEFAULT_NORMS)); }

  // Ставка ступени для заданного % выполнения плана.
  function stepValue(ступени, pct) {
    var r = (ступени[0] || {}).ставка || 0;
    for (var i = 0; i < ступени.length; i++) {
      if (pct >= ступени[i].порог) r = ступени[i].ставка;
    }
    return r;
  }

  // Ближайшая ступень выше текущего значения (или null).
  function nextStep(ступени, pct) {
    for (var i = 0; i < ступени.length; i++) {
      if (ступени[i].порог > pct) return ступени[i];
    }
    return null;
  }

  global.ROP_NORMS = {
    DEFAULT_NORMS: DEFAULT_NORMS,
    load: norms,
    gradeRate: stepValue,
    nextGrade: nextStep
  };
})(window);
