/**
 * Шаблон калькулятора РОПа (руководитель отдела продаж) — нормы.
 * Обезличенный черновик: не привязан к клиенту.
 *
 * Задано Русланом (19.11): норма конверсии 75%, норма среднего чека 20 000 ₽,
 * оклад 60 000 ₽, вилка зарплаты 80–120 тыс. ₽, по KPI есть гарантированный
 * минимум. Остальное (разбивка KPI-части на три слагаемых по 20 000 ₽ и
 * суммы ступеней плана куста) подобрано под вилку и не согласовано.
 *
 * Модель: ЗП РОПа = оклад + KPI-часть.
 *   KPI-часть = max(минималка, премия за план куста + KPI «чек» + KPI «конверсия»)
 *
 *   • Минимум = 60 000 + минималка 20 000 = 80 000 ₽.
 *   • Максимум = 60 000 + 20 000 (план куста, высшая ступень)
 *                + 20 000 (чек) + 20 000 (конверсия) = 120 000 ₽.
 *   Суммы фиксированные, от выручки не зависят.
 *
 * Ступени: массив {порог, сумма}, отсортирован по порогу. Первый элемент —
 * базовая ступень (порог 0, «ниже всех порогов»).
 */
(function (global) {
  var DEFAULT_NORMS = {
    оклад: 60000,
    минималкаKpi: 20000,    // гарантированный минимум KPI-части
    ступени: [
      { порог: 0,   сумма: 0 },       // план куста < 80%
      { порог: 80,  сумма: 7000 },
      { порог: 100, сумма: 14000 },
      { порог: 110, сумма: 20000 }    // перевыполнение
    ],
    kpiЧек: {
      план: 20000,     // норма среднего чека, ₽
      премия: 20000    // выплачивается, если факт не ниже нормы
    },
    kpiКонверсия: {
      план: 75,        // норма конверсии, %
      премия: 20000    // выплачивается, если факт не ниже нормы
    }
  };

  function norms() { return JSON.parse(JSON.stringify(DEFAULT_NORMS)); }

  // Сумма ступени для заданного % выполнения плана.
  function stepValue(ступени, pct) {
    var r = (ступени[0] || {}).сумма || 0;
    for (var i = 0; i < ступени.length; i++) {
      if (pct >= ступени[i].порог) r = ступени[i].сумма;
    }
    return r;
  }

  // Ближайшая ступень выше текущего значения (или null).
  function nextStep(ступени, pct) {
    for (var i = 0; i < ступени.length; i++) {
      if (ступени[i].порог > pct) return ступени[i];
    }
    return null;
  }

  global.ROP_NORMS = {
    DEFAULT_NORMS: DEFAULT_NORMS,
    load: norms,
    stepAmount: stepValue,
    nextStep: nextStep
  };
})(window);
