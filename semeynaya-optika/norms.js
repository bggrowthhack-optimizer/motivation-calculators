/**
 * Семейная оптика — нормы (константы политики оплаты). Черновик для обсуждения
 * с Галиной, цифры не утверждены.
 *
 * Модель (чат с Русланом, 27.10, пересмотрена в тот же день): ЗП консультанта =
 * оклад + % от личной выручки. Ставка складывается из двух независимых частей:
 *
 *   • ГРЕЙД по личному выполнению плана (лестница, как обычно):
 *       личный_% = личная_выручка / личный_план × 100
 *       базовая_ставка = ставка грейда по личному_%
 *   • НАДБАВКА за работу всей сети/филиала с базой — отдельная лестница ступеней
 *     от ОБЩЕГО % клиентов, вернувшихся из базы за месяц (не личный показатель
 *     консультанта, один на всех — как план филиала у Модного взгляда):
 *       итоговая_ставка = базовая_ставка + надбавка(общий_%_возврата)
 *
 * Первая версия (ставка грейда росла по ВЗВЕШЕННОЙ личной выручке, где заказ
 * от клиента «из базы» считался тяжелее) отклонена 27.10: в рознице постоянно
 * будет спорно, кто именно вернул конкретного клиента — звонил один, а в зале
 * его обслужил другой. Поэтому работа с базой теперь не требует разбивки
 * личной выручки на «обычную» и «из базы» и не завязана на то, кто именно
 * сделал звонок — это общий показатель сети, который двигает ставку
 * ВСЕМ консультантам сразу, когда база в целом работает лучше. Личная
 * выручка в калькуляторе теперь одна цифра, без разбивки.
 *
 * Средний чек — всё ещё не отдельная премия, а ОГРАНИЧИТЕЛЬ: если факт ниже
 * порога (% от планового чека), итоговая премия урезается до указанной доли.
 *
 * Оклад, грейды, ступени за базу и параметры чека — ПРИМЕРНЫЕ числа для старта
 * разговора с Галиной. Отправная точка по базе — её же цифра (сейчас ~9%
 * возврата), ступени поставлены чуть выше, чтобы было видно, за что бороться.
 *
 * Правится на /semeynaya-optika/settings/ (localStorage одного браузера)
 * либо здесь в коде, чтобы стало боевым для всех.
 *
 * Грейды и ступени — массивы {порог, ставка}, отсортированы по порогу.
 * Первый элемент — базовое значение (порог 0, «ниже всех порогов»).
 * Значение = значение последней ступени, чей порог ≤ входному %.
 */
(function (global) {
  var STORAGE_KEY = 'semeynaya-optika:norms';

  var DEFAULT_NORMS = {
    оклад: 30000,
    грейды: [
      { порог: 0,   ставка: 0.03 },  // личный план < 80%
      { порог: 80,  ставка: 0.05 },
      { порог: 100, ставка: 0.07 },
      { порог: 110, ставка: 0.09 }   // перевыполнение
    ],
    базаСтупени: [
      { порог: 0,  ставка: 0 },      // ниже 12% возврата — без надбавки
      { порог: 12, ставка: 0.005 },  // +0,5 п.п. к ставке
      { порог: 16, ставка: 0.010 },
      { порог: 20, ставка: 0.015 }
    ],
    чек: {
      план: 5800,        // плановый средний чек, ₽
      порогДоли: 90,      // ниже этой % от планового чека — премия урезается
      урезаниеДо: 70       // до какой % от расчётной премии урезаем при провале чека
    }
  };

  function isObj(x) { return x && typeof x === 'object' && !Array.isArray(x); }

  function merge(base, over) {
    if (Array.isArray(base)) return Array.isArray(over) ? over.slice() : base.slice();
    var out = isObj(base) ? Object.assign({}, base) : base;
    Object.keys(over || {}).forEach(function (k) {
      out[k] = (isObj(base[k]) && isObj(over[k])) || (Array.isArray(base[k]) && Array.isArray(over[k]))
        ? merge(base[k], over[k])
        : over[k];
    });
    return out;
  }

  function readOverride() {
    try {
      var raw = localStorage.getItem(STORAGE_KEY);
      return raw ? JSON.parse(raw) : null;
    } catch (e) { return null; }
  }

  function load() {
    var over = readOverride();
    return over ? merge(DEFAULT_NORMS, over) : merge(DEFAULT_NORMS, {});
  }

  function save(norms) {
    try { localStorage.setItem(STORAGE_KEY, JSON.stringify(norms)); return true; }
    catch (e) { return false; }
  }

  function reset() {
    try { localStorage.removeItem(STORAGE_KEY); } catch (e) {}
  }

  function isCustom() { return !!readOverride(); }

  // ── общая логика ступеней (используется и для грейдов, и для надбавки за базу) ──
  function stepValue(ступени, pct) {
    var r = (ступени[0] || {}).ставка || 0;
    for (var i = 0; i < ступени.length; i++) {
      if (pct >= ступени[i].порог) r = ступени[i].ставка;
    }
    return r;
  }
  function nextStep(ступени, pct) {
    for (var i = 0; i < ступени.length; i++) {
      if (ступени[i].порог > pct) return ступени[i];
    }
    return null;
  }

  global.SO_NORMS = {
    STORAGE_KEY: STORAGE_KEY,
    DEFAULT_NORMS: DEFAULT_NORMS,
    load: load,
    save: save,
    reset: reset,
    isCustom: isCustom,
    gradeRate: stepValue,
    nextGrade: nextStep
  };
})(window);
